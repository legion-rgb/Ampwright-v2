"""Phase B check, no AWR needed: tidy and spec checks on recorded fixtures.
Run: uv run --with "mcp>=1.2,<2" --with pywin32 python tests/test_checks.py
(fixtures are regenerated by `python tests/test_checks.py --regen`)"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FIX = os.path.join(HERE, "fixtures")
sys.path.insert(0, os.path.join(HERE, "..", "checks"))
import check_spec  # noqa: E402
import check_tidy  # noqa: E402


def _el(id_, *pins):  # list_elements row shape
    return {"name": id_, "id": id_, "model": id_[0], "parameters": [],
            "pins": [{"pin": i, "net": i, "connected": True, "x": x, "y": y} for i, (x, y) in enumerate(pins, 1)]}


def _w(x1, y1, x2, y2, net):  # list_wires row shape
    return {"x1": x1, "y1": y1, "x2": x2, "y2": y2, "net": net}


ELEMS = [_el("R1", (0, 0), (1000, 0)), _el("R2", (3000, 0), (4000, 0)), _el("GND1", (0, 1000))]
GOOD = [_w(1000, 0, 3000, 0, "N1"), _w(2000, 0, 2000, 1000, "N1"), _w(0, 0, 0, 1000, "N2"), _w(4000, 0, 5000, 0, "N3")]
TIDY = {
    "tidy_pass": GOOD,
    "tidy_cross": GOOD + [_w(2500, -500, 2500, 500, "N9")],  # crosses the N1 wire
    "tidy_body": GOOD + [_w(500, -1000, 500, 1000, "N5")],  # through R1
    "tidy_pin": GOOD[:3] + [_w(4000, -1000, 4000, 1000, "N6")],  # over R2:2
}


def _trace(name, xs, ys):
    return {"measurement": name, "label": name, "x_unit": "Hz", "y_unit": "dB", "x": xs, "y": ys, "truncated": False}


GOALS = [
    {"id": "s11", "metric": "S11_dB", "graph": "g_s", "measurement": "S(1,1)", "over_hz": [1.5e9, 2.5e9], "op": "<=", "value": -10},
    {"id": "id", "metric": "Id_A", "graph": "g_iv", "at": {"Vds": 3.0}, "op": "within", "value": 0.020, "tol": 0.001},
    {"id": "gain", "metric": "S21_dB", "graph": "g_s", "measurement": "DB(|S(2,1)|)", "over_hz": [1.5e9, 2.5e9], "op": ">=", "value": 15},
]
SPEC = {"name": "t", "class": "bias", "schematic": "s", "goals": GOALS}
FREQ = [1e9, 1.5e9, 2e9, 2.5e9, 3e9]


def _data(s11, s21, id_at3):
    return {"g_s": [_trace("DB(|S(1,1)|)", FREQ, s11), _trace("DB(|S(2,1)|)", FREQ, s21)],
            "g_iv": [_trace("IV", [2.0, 4.0], [0.010, id_at3 * 2 - 0.010])]}  # interpolates to id_at3 at Vds=3


DATA = {"spec_pass": _data([-3, -12, -15, -11, -4], [10, 16, 17, 16, 10], 0.0205),
        "spec_fail": _data([-3, -12, -8, -11, -4], [10, 16, 12, 16, 10], 0.0250)}


def regen():
    os.makedirs(FIX, exist_ok=True)
    for k, ws in TIDY.items():
        json.dump({"elements": ELEMS, "wires": ws}, open(os.path.join(FIX, k + ".json"), "w"), indent=1)
    for k, d in DATA.items():
        json.dump(SPEC, open(os.path.join(FIX, k + "_spec.json"), "w"), indent=1)
        json.dump(d, open(os.path.join(FIX, k + "_data.json"), "w"), indent=1)


def load(name):
    return json.load(open(os.path.join(FIX, name + ".json")))


if "--regen" in sys.argv:
    regen()

kinds = {}
for k in TIDY:
    f = load(k)
    kinds[k] = sorted({i["kind"] for i in check_tidy.check(f["elements"], f["wires"])})
assert kinds == {"tidy_pass": [], "tidy_cross": ["crossing"], "tidy_body": ["body"], "tidy_pin": ["pin"]}, kinds
# overlap of two different-net wires, and a same-net X crossing
assert [i["kind"] for i in check_tidy.check([], [_w(0, 0, 2000, 0, "A"), _w(1000, 0, 3000, 0, "B")])] == ["overlap"]
assert [i["kind"] for i in check_tidy.check([], [_w(0, 500, 2000, 500, "A"), _w(1000, 0, 1000, 1000, "A")])] == ["crossing"]
assert check_tidy.check([], [_w(0, 500, 2000, 500, "A"), _w(1000, 500, 1000, 1000, "A")]) == []  # same-net T is fine

p = evaluate = check_spec.evaluate(load("spec_pass_spec"), load("spec_pass_data"))
assert p["_sim"] == "ok" and all(p[g["id"]]["meets"] for g in GOALS), p
assert abs(p["s11"]["measured"] - -11) < 1e-9 and abs(p["id"]["measured"] - 0.0205) < 1e-9 and p["gain"]["measured"] == 16, p
f = check_spec.evaluate(load("spec_fail_spec"), load("spec_fail_data"))
assert [f[g["id"]]["meets"] for g in GOALS] == [False, False, False], f
# two traces and no "measurement" must be an error for that goal, not a guess
amb = check_spec.evaluate({"goals": [{"id": "x", "graph": "g_s", "over_hz": [1e9, 3e9], "op": "<=", "value": 0}]}, load("spec_pass_data"))
assert amb["x"]["meets"] is False and "error" in amb["x"]["how"], amb
# an empty trace fails that goal, it must not crash the evaluation
emp = check_spec.evaluate({"goals": [{"id": "e", "graph": "g", "over_hz": [1, 2], "op": "<=", "value": 0}]}, {"g": [_trace("m", [], [])]})
assert emp["e"]["meets"] is False and "no points" in emp["e"]["how"], emp
# a truncated trace fails loudly instead of reading as "outside x range" (rlc_notch, 21 Nov)
tr = check_spec.evaluate({"goals": [{"id": "t", "graph": "g", "at": {"f": 1}, "op": "<=", "value": 0}]},
                         {"g": [{**_trace("m", [0, 2], [-1, -1]), "truncated": True}]})
assert tr["t"]["meets"] is False and "truncated" in tr["t"]["how"], tr
# the hub unwraps a one-item list into the bare item; call_list must wrap it back (found live, 21 Nov)
import _awr
_awr.call = lambda tool, **a: {"measurement": "m", "x": [1], "y": [2]}
assert _awr.call_list("graph_data", graph="g") == [{"measurement": "m", "x": [1], "y": [2]}]
_awr.call = lambda tool, **a: []
assert _awr.call_list("list_wires", schematic="s") == []
print("OK")
